/**
 * Deduplicated, safety-filtered active prompts.
 */
export function getActivePrompts(): ExternalPrompt[] {
  return normalizedExternalPrompts.filter(
    (p) => p.safetyStatus === "safe" && !isPromptBlocked(p.id, p.sourceUrl)
  );
}

export function getPromptById(id: string): ExternalPrompt | undefined {
  return getActivePrompts().find((p) => p.id === id);
}

export function getPromptsBySource(sourceName: string): ExternalPrompt[] {
  const norm = sourceName.toLowerCase();
  return getActivePrompts().filter((p) => p.sourceName.toLowerCase().includes(norm));
}

export function getPromptsByCategory(category: PromptCategory): ExternalPrompt[] {
  return getActivePrompts().filter((p) => p.category === category);
}

export function getPromptsByPlatform(platform: PromptPlatform): ExternalPrompt[] {
  return getActivePrompts().filter(
    (p) => p.platform.includes(platform) || p.platform.includes("Universal")
  );
}

export function getPromptStaticParams(): Array<{ id: string }> {
  return getActivePrompts().map((p) => ({ id: p.id }));
}
