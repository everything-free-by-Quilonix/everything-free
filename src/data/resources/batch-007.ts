/** When this batch was compiled. Used for submittedAt / updatedAt only, never as a verification date. */
const COMPILED_ON = "2026-10-01";

const COMPILATION_NOTE =
  "Compiled for developer expansion 001 from the provider's own documentation, terms, pricing pages or official repository. " +
  "This was research for the listing, not a verification pass: no checks are recorded and every fact is unverified.";

type ListableStatus = Extract<FreeStatus, "FREE" | "FREE_TIER" | "OPEN_SOURCE" | "PERSONAL_FREE">;

/** What the provider's own pages said about access, in their words. Never copied into tri-state facts. */
interface DocumentedAccess {
  key?: string;
  signup?: string;
  card?: string;
  commercial?: string;
}

type BatchSeed = Omit<
  ResourceSeed,
  | "freeStatus"
  | "openSource"
  | "requiresAccount"
  | "requiresCreditCard"
  | "commercialUse"
  | "personalUse"
  | "verificationStatus"
  | "verificationNotes"
  | "verificationSources"
  | "verificationChecks"
  | "verifiedBy"
  | "lastVerifiedAt"
  | "compilationNotes"
  | "submittedAt"
  | "updatedAt"
> & {
  freeStatus: ListableStatus;
  /** Defaults to true only for OPEN_SOURCE. */
  openSource?: boolean;
  access?: DocumentedAccess;
  /** A listing-specific compilation caveat, appended to the batch note. */
  note?: string;
};

function accessSentence(access: DocumentedAccess | undefined): string {
  if (!access) return "";
  const parts = [
    access.key && `API key ${access.key}`,
    access.signup && `sign-up ${access.signup}`,
    access.card && `credit card ${access.card}`,
    access.commercial && `commercial use ${access.commercial}`,
  ].filter(Boolean);
  return parts.length ? ` Access as described by the provider when compiled (unverified): ${parts.join("; ")}.` : "";
}

function entry({ access, note, ...seed }: BatchSeed): ResourceSeed {
  return {
    ...seed,
    openSource: seed.openSource ?? seed.freeStatus === "OPEN_SOURCE",
    requiresAccount: "unknown",
    requiresCreditCard: "unknown",
    commercialUse: "unknown",
    personalUse: "unknown",
    verificationStatus: "UNVERIFIED",
    compilationNotes: `${COMPILATION_NOTE}${accessSentence(access)}${note ? ` ${note}` : ""}`,
    submittedAt: COMPILED_ON,
    updatedAt: COMPILED_ON,
  };
}

