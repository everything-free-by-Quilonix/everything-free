/**
 * Batch 002 records unverified entries compiled from project-controlled sites,
 * repositories, and official government/educational portals.
 * Evidence-sensitive facts stay unknown until a later verification pass.
 */
type BatchSeed = Omit<
  ResourceSeed,
  "requiresAccount" | "requiresCreditCard" | "commercialUse" | "personalUse" | "verificationStatus" | "compilationNotes"
>;

function unverified(seed: BatchSeed): ResourceSeed {
  return {
    ...seed,
    requiresAccount: "unknown",
    requiresCreditCard: "unknown",
    commercialUse: "unknown",
    personalUse: "unknown",
    verificationStatus: "UNVERIFIED",
    compilationNotes:
      "Compiled from the project's official site, portal or source repository where available. No verification pass has been recorded.",
  };
}

function openSource(seed: Omit<BatchSeed, "freeStatus" | "openSource">): ResourceSeed {
  return unverified({ ...seed, freeStatus: "OPEN_SOURCE", openSource: true });
}

