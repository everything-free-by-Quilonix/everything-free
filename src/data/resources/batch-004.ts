type BatchSeed = Omit<
  ResourceSeed,
  "requiresAccount" | "requiresCreditCard" | "commercialUse" | "personalUse" | "verificationStatus" | "compilationNotes" | "platforms"
> & {
  platforms?: Platform[];
};

function unverified(seed: BatchSeed): ResourceSeed {
  return {
    ...seed,
    platforms: seed.platforms ?? ["BROWSER"],
    requiresAccount: "unknown",
    requiresCreditCard: "unknown",
    commercialUse: "unknown",
    personalUse: "unknown",
    verificationStatus: "UNVERIFIED",
    compilationNotes:
      "Compiled from project documentation, portal entries, and provider pricing terms. No verification pass has been recorded.",
  };
}

function openSource(seed: Omit<BatchSeed, "freeStatus" | "openSource">): ResourceSeed {
  return unverified({ ...seed, freeStatus: "OPEN_SOURCE", openSource: true });
}

function freeWeb(seed: Omit<BatchSeed, "freeStatus" | "openSource"> & { openSource?: boolean; license?: string; limitations?: string[] }): ResourceSeed {
  return unverified({
    ...seed,
    freeStatus: "FREE",
    openSource: seed.openSource ?? false,
    platforms: seed.platforms ?? ["BROWSER"],
  });
}

function freeTier(seed: Omit<BatchSeed, "freeStatus" | "openSource"> & { limitations: string[]; openSource?: boolean; license?: string; pricingUrl?: string }): ResourceSeed {
  return unverified({
    ...seed,
    freeStatus: "FREE_TIER",
    openSource: seed.openSource ?? false,
    platforms: seed.platforms ?? ["BROWSER"],
  });
}

function personalFree(seed: Omit<BatchSeed, "freeStatus" | "openSource"> & { limitations: string[]; openSource?: boolean; license?: string }): ResourceSeed {
  return unverified({
    ...seed,
    freeStatus: "PERSONAL_FREE",
    openSource: seed.openSource ?? false,
    platforms: seed.platforms ?? ["BROWSER"],
  });
}

