/** When this batch was compiled. Used for submittedAt / updatedAt only, never as a verification date. */
const COMPILED_ON = "2026-10-01";

const COMPILATION_NOTE =
  "Compiled for batch 006 from the provider's own website, documentation, licence or pricing pages. " +
  "This was research for the listing, not a verification pass: no checks are recorded and every fact is unverified.";

type ListableStatus = Extract<FreeStatus, "FREE" | "FREE_TIER" | "OPEN_SOURCE" | "PERSONAL_FREE">;

type BatchSeed = Omit<
  ResourceSeed,
  | "freeStatus"
  | "openSource"
  | "requiresAccount"
  | "requiresCreditCard"
  | "commercialUse"
  | "personalUse"
  | "verificationStatus"
  | "verificationNotes"
  | "verificationSources"
  | "verificationChecks"
  | "verifiedBy"
  | "lastVerifiedAt"
  | "compilationNotes"
  | "submittedAt"
  | "updatedAt"
> & {
  freeStatus: ListableStatus;
  /** Defaults to true only for OPEN_SOURCE. */
  openSource?: boolean;
  /** A listing-specific compilation caveat, appended to the batch note. */
  note?: string;
};

function entry({ note, ...seed }: BatchSeed): ResourceSeed {
  return {
    ...seed,
    openSource: seed.openSource ?? seed.freeStatus === "OPEN_SOURCE",
    requiresAccount: "unknown",
    requiresCreditCard: "unknown",
    commercialUse: "unknown",
    personalUse: "unknown",
    verificationStatus: "UNVERIFIED",
    compilationNotes: note ? `${COMPILATION_NOTE} ${note}` : COMPILATION_NOTE,
    submittedAt: COMPILED_ON,
    updatedAt: COMPILED_ON,
  };
}

