/** Get a command by its slug/id */
export function getAIImageCommand(id: string): AIImageCommand | undefined {
  return aiImageCommandsMap.get(id);
}

/** Get all commands by category */
export function getAIImageCommandsByCategory(category: CommandCategory): AIImageCommand[] {
  return aiImageCommands.filter((cmd) => cmd.category === category);
}

/** Get all unique categories with counts */
export function getCategoryCounts(): Array<{ category: CommandCategory; count: number }> {
  const counts = new Map<CommandCategory, number>();
  for (const cmd of aiImageCommands) {
    counts.set(cmd.category, (counts.get(cmd.category) ?? 0) + 1);
  }
  return Array.from(counts.entries()).map(([category, count]) => ({ category, count }));
}

/** Get statistics for the command library */
export function getCommandLibraryStats() {
  const total = aiImageCommands.length;
  let verifiedCount = 0;
  let promptModifierCount = 0;
  let styleReferenceCount = 0;
  let unsupportedCount = 0;

  for (const cmd of aiImageCommands) {
    if (cmd.verification.status === "verified") verifiedCount++;
    if (cmd.platforms.chatgpt === "prompt_modifier" || cmd.platforms.gemini === "prompt_modifier") {
      promptModifierCount++;
    }
    if (cmd.platforms.chatgpt === "style_reference" || cmd.platforms.gemini === "style_reference") {
      styleReferenceCount++;
    }
    if (cmd.verification.status === "unsupported" || cmd.platforms.chatgpt === "unsupported") {
      unsupportedCount++;
    }
  }

  return {
    total,
    verifiedCount,
    promptModifierCount,
    styleReferenceCount,
    unsupportedCount,
  };
}
