#!/usr/bin/env node
/**
 * Writes `src/features/ai/model-manifest.ts`: every file the private AI chat's
 * models are made of, with its size and SHA-256.
 *
 * Why it exists: the chat can save a model to a file on the visitor's device and
 * load it back later without the internet. A file from a device (or from a friend)
 * cannot be trusted as it is, and part of it is the model's compiled WebAssembly,
 * which runs in the browser. So an imported file is accepted only if every part
 * matches a fingerprint recorded here, from the official sources.
 *
 * Sources: Hugging Face's own SHA-256 for large (LFS) files, and a download and hash
 * of everything else, including the WebAssembly library from GitHub.
 *
 *   npm run ai:manifest            # rewrite the manifest
 *   npm run ai:manifest -- --check # fail if it is out of date
 *
 * Needs the network. The build never runs it, so a build cannot fail because
 * Hugging Face or GitHub is unreachable.
 */

import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { argv, exit } from "node:process";
import { prebuiltAppConfig } from "@mlc-ai/web-llm";

const MODELS_FILE = new URL("../src/features/ai/models.ts", import.meta.url);
const TARGET = new URL("../src/features/ai/model-manifest.ts", import.meta.url);
const check = argv.includes("--check");

const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex");

async function download(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url} answered ${response.status}`);
  return Buffer.from(await response.arrayBuffer());
}

function modelBase(record) {
  let url = record.model.endsWith("/") ? record.model : `${record.model}/`;
  if (!/.+\/resolve\/.+\//.test(url)) url += "resolve/main/";
  return new URL(url).href;
}

const source = await readFile(MODELS_FILE, "utf8");
const ids = [...source.matchAll(/^\s+id: "([^"]+)",$/gm)].map((m) => m[1]);
if (ids.length === 0) throw new Error("no model ids found in models.ts");

const manifest = {};
for (const id of ids) {
  const record = prebuiltAppConfig.model_list.find((entry) => entry.model_id === id);
  if (!record) throw new Error(`${id} is not a WebLLM prebuilt model`);
  const base = modelBase(record);
  const repo = new URL(record.model).pathname.replace(/^\/|\/$/g, "");

  const tree = await (await fetch(`https://huggingface.co/api/models/${repo}/tree/main`)).json();
  const files = [];
  for (const entry of tree) {
    if (entry.type !== "file" || /^(README\.md|\.gitattributes)$/.test(entry.path)) continue;
    const url = new URL(entry.path, base).href;
    const sha = entry.lfs?.oid ?? sha256(await download(url));
    files.push({ url, size: entry.lfs?.size ?? entry.size, sha256: sha });
  }
  const wasm = await download(record.model_lib);
  files.push({ url: record.model_lib, size: wasm.length, sha256: sha256(wasm) });
  files.sort((a, b) => a.url.localeCompare(b.url));
  manifest[id] = files;
  const mb = files.reduce((sum, f) => sum + f.size, 0) / 1e6;
  console.log(`${id}: ${files.length} files, ${mb.toFixed(1)} MB`);
}

const output = `/*
 * GENERATED by scripts/ai-model-manifest.mjs. Do not edit by hand: run \`npm run ai:manifest\`.
 *
 * Every file each chat model is made of, with its size and SHA-256, from Hugging
 * Face and GitHub. A model file imported from the visitor's device is accepted only
 * if every part matches (features/ai/logic/model-file.ts).
 */

export interface ManifestFile {
  url: string;
  size: number;
  sha256: string;
}

export const modelManifest: Record<string, readonly ManifestFile[]> = ${JSON.stringify(manifest, null, 2)};
`;

const current = await readFile(TARGET, "utf8").catch(() => "");
if (check) {
  if (current !== output) {
    console.error("✗ src/features/ai/model-manifest.ts is out of date. Run `npm run ai:manifest`.");
    exit(1);
  }
  console.log("✓ Model manifest is current");
} else {
  await writeFile(TARGET, output, "utf8");
  console.log("✓ Wrote src/features/ai/model-manifest.ts");
}
