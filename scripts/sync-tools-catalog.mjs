#!/usr/bin/env node
/**
 * Refreshes the snapshot of the Everything.Free Tools catalogue.
 *
 * The tools site publishes `/tools.json`, generated from its own registry. This
 * script reads it, checks its shape, and writes `src/data/tools-site.ts`, which is
 * committed. The build reads only that committed file: it never makes a network
 * request, so a build is reproducible and cannot fail because another site is down.
 *
 *   npm run sync:tools                     # deployed site
 *   npm run sync:tools -- ../everything-free-tools/out/tools.json   # a local build
 *   npm run sync:tools -- --check          # fail if the snapshot is out of date
 *
 * The two projects share no code: this is data, read from a public URL.
 */

import { readFile, writeFile } from "node:fs/promises";
import { argv, exit } from "node:process";

const DEFAULT_SOURCE = "https://everything-free-by-quilonix.github.io/everything-free-tools/tools.json";
const TARGET = new URL("../src/data/tools-site.ts", import.meta.url);
const SUPPORTED_VERSION = 1;

const args = argv.slice(2);
const check = args.includes("--check");
const source = args.find((arg) => !arg.startsWith("--")) ?? DEFAULT_SOURCE;

async function load(from) {
  if (/^https:\/\//.test(from)) {
    const response = await fetch(from, { headers: { Accept: "application/json" } });
    if (!response.ok) throw new Error(`${from} answered ${response.status}`);
    return response.json();
  }
  return JSON.parse(await readFile(from, "utf8"));
}

/** A light shape check; the full validation runs in `config/tools-site.ts` at build time. */
function problems(catalog) {
  const found = [];
  if (catalog?.version !== SUPPORTED_VERSION)
    found.push(`version ${catalog?.version} is not ${SUPPORTED_VERSION}; update this script and config/tools-site.ts`);
  if (!Array.isArray(catalog?.tools) || catalog.tools.length === 0) found.push("no tools");
  if (!Array.isArray(catalog?.categories) || catalog.categories.length === 0) found.push("no categories");
  return found;
}

/** Keeps only the fields this site uses, in a fixed order, so diffs stay readable. */
function slim(catalog) {
  return {
    version: catalog.version,
    name: catalog.name,
    url: catalog.url,
    categories: catalog.categories.map(({ slug, name, tagline, description, url, toolCount }) => ({
      slug,
      name,
      tagline,
      description,
      url,
      toolCount,
    })),
    tools: catalog.tools.map(({ slug, name, description, url, category, alsoIn, processing, formats, tags }) => ({
      slug,
      name,
      description,
      url,
      category,
      alsoIn,
      processing,
      formats,
      tags,
    })),
  };
}

function render(catalog) {
  return `/*
 * GENERATED by scripts/sync-tools-catalog.mjs from ${source === DEFAULT_SOURCE ? DEFAULT_SOURCE : "the tools site's tools.json"}.
 * Do not edit by hand: run \`npm run sync:tools\`. Validated by config/tools-site.ts.
 */

export const toolsSiteCatalog: unknown = ${JSON.stringify(slim(catalog), null, 2)};
`;
}

try {
  const catalog = await load(source);
  const found = problems(catalog);
  if (found.length > 0) throw new Error(`the catalogue at ${source} is not usable:\n  - ${found.join("\n  - ")}`);
  const next = render(catalog);
  const current = await readFile(TARGET, "utf8").catch(() => "");

  if (check) {
    // The header names the source, so compare only the data.
    const body = (text) => text.slice(text.indexOf("export const"));
    if (body(current) !== body(next)) {
      console.error("✗ src/data/tools-site.ts is out of date. Run `npm run sync:tools`.");
      exit(1);
    }
    console.log(`✓ Tools catalogue snapshot is current (${catalog.tools.length} tools)`);
  } else if (current === next) {
    console.log(`✓ Tools catalogue unchanged (${catalog.tools.length} tools)`);
  } else {
    await writeFile(TARGET, next, "utf8");
    console.log(`✓ Wrote src/data/tools-site.ts: ${catalog.tools.length} tools in ${catalog.categories.length} categories`);
  }
} catch (error) {
  console.error(`✗ ${error instanceof Error ? error.message : error}`);
  exit(1);
}
